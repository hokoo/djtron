'use strict';

const fs = require('fs');
const path = require('path');

const ROOT_DIR = path.resolve(__dirname, '..');
const SHARED_DIR = path.join(ROOT_DIR, 'shared', 'playback');
const LIB_DIR = path.join(ROOT_DIR, 'lib', 'playback');

const FILES = [
  'audioEngine',
  'rolePolicy',
  'commandBus',
  'playlistRepository',
  'playlistEditor',
  'playbackController',
];

function normalizeNamedSpecifiers(value) {
  return value
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean);
}

function collectNamedExports(specifierList, exportedNames) {
  normalizeNamedSpecifiers(specifierList).forEach((entry) => {
    const match = entry.match(/^([A-Za-z_$][A-Za-z0-9_$]*)(?:\s+as\s+([A-Za-z_$][A-Za-z0-9_$]*))?$/);
    if (!match) return;
    const exportedName = match[2] || match[1];
    exportedNames.add(exportedName);
  });
}

function transpileEsmToCjs(sourceCode) {
  const exportedNames = new Set();
  let output = sourceCode;

  output = output.replace(
    /^import\s+\{\s*([^}]+?)\s*\}\s+from\s+['"](\.\/[^'"]+)\.js['"];\s*$/gm,
    (_, specifiers, importPath) => `const { ${normalizeNamedSpecifiers(specifiers).join(', ')} } = require('${importPath}');`,
  );

  output = output.replace(/^export\s+class\s+([A-Za-z_$][A-Za-z0-9_$]*)/gm, (_, className) => {
    exportedNames.add(className);
    return `class ${className}`;
  });

  output = output.replace(/^export\s+function\s+([A-Za-z_$][A-Za-z0-9_$]*)/gm, (_, functionName) => {
    exportedNames.add(functionName);
    return `function ${functionName}`;
  });

  output = output.replace(/^export\s+const\s+([A-Za-z_$][A-Za-z0-9_$]*)/gm, (_, constantName) => {
    exportedNames.add(constantName);
    return `const ${constantName}`;
  });

  output = output.replace(/^export\s+\{\s*([^}]+?)\s*\};?\s*$/gm, (_, specifiers) => {
    collectNamedExports(specifiers, exportedNames);
    return '';
  });

  if (/^\s*export\s+/m.test(output)) {
    throw new Error('Unsupported export syntax detected while syncing playback modules');
  }

  const moduleExports = `module.exports = {\n  ${Array.from(exportedNames).join(',\n  ')},\n};\n`;
  return [
    "'use strict';",
    '',
    '// AUTO-GENERATED from shared/playback/*.js by scripts/sync-playback-lib.js',
    '// Do not edit this file manually.',
    '',
    output.trimEnd(),
    '',
    moduleExports,
  ].join('\n');
}

function syncFile(baseName) {
  const sourcePath = path.join(SHARED_DIR, `${baseName}.js`);
  const targetPath = path.join(LIB_DIR, `${baseName}.js`);
  const sourceCode = fs.readFileSync(sourcePath, 'utf8');
  const transpiled = transpileEsmToCjs(sourceCode);
  fs.writeFileSync(targetPath, transpiled, 'utf8');
}

for (const file of FILES) {
  syncFile(file);
}
